"""
Metrics for evaluating explanations in ExplainableCropAI.

This module implements quantitative metrics for assessing the quality
of visual and textual explanations generated by the system.
"""

import numpy as np
import torch
from scipy.ndimage import gaussian_filter
from sklearn.metrics import precision_score, recall_score, f1_score
import nltk
from nltk.translate.bleu_score import sentence_bleu
from nltk.tokenize import word_tokenize


class VisualExplanationEvaluator:
    """
    Evaluator for visual explanation techniques like Grad-CAM.
    
    Implements metrics to assess explanation quality, faithfulness,
    and localization accuracy.
    """
    
    def __init__(self, model=None):
        """
        Initialize the visual explanation evaluator.
        
        Args:
            model: PyTorch model (optional, for faithfulness evaluation)
        """
        self.model = model
    
    def evaluate_localization(self, explanation_mask, ground_truth_mask, threshold=0.5):
        """
        Evaluate how well the explanation localizes the disease.
        
        Args:
            explanation_mask (np.ndarray): Explanation heatmap
            ground_truth_mask (np.ndarray): Ground truth segmentation mask
            threshold (float): Threshold for binarizing the heatmap
            
        Returns:
            dict: Localization metrics
        """
        # Ensure masks are binary
        binary_explanation = (explanation_mask > threshold).astype(np.uint8)
        binary_ground_truth = (ground_truth_mask > 0).astype(np.uint8)
        
        # Calculate intersection and union
        intersection = np.logical_and(binary_explanation, binary_ground_truth).sum()
        union = np.logical_or(binary_explanation, binary_ground_truth).sum()
        
        # Calculate metrics
        iou = intersection / union if union > 0 else 0
        precision = intersection / binary_explanation.sum() if binary_explanation.sum() > 0 else 0
        recall = intersection / binary_ground_truth.sum() if binary_ground_truth.sum() > 0 else 0
        f1 = 2 * precision * recall / (precision + recall) if (precision + recall) > 0 else 0
        
        return {
            "iou": iou,
            "precision": precision,
            "recall": recall,
            "f1_score": f1
        }
    
    def evaluate_faithfulness(self, image, explanation_mask, model=None, class_idx=None, threshold=0.5):
        """
        Evaluate faithfulness of the explanation to the model's decision.
        
        Uses the Insertion and Deletion metrics (Petsiuk et al., 2018).
        
        Args:
            image (torch.Tensor): Input image tensor
            explanation_mask (np.ndarray): Explanation heatmap
            model: PyTorch model (uses self.model if None)
            class_idx (int): Class index to evaluate
            threshold (float): Threshold for perturbation
            
        Returns:
            dict: Faithfulness metrics
        """
        if model is None:
            model = self.model
        
        if model is None:
            return {
                "insertion_auc": None,
                "deletion_auc": None,
                "note": "Model not provided for faithfulness evaluation"
            }
        
        # Normalize mask to [0, 1]
        norm_mask = explanation_mask - explanation_mask.min()
        norm_mask = norm_mask / (norm_mask.max() + 1e-8)
        
        # Get original prediction
        with torch.no_grad():
            orig_output, _ = model(image)
            orig_probs = torch.nn.functional.softmax(orig_output, dim=1)
            
            if class_idx is None:
                class_idx = orig_probs.argmax(dim=1).item()
            
            orig_score = orig_probs[0, class_idx].item()
        
        # Insertion metric (gradually reveal image based on importance)
        insertion_scores = self._compute_insertion_scores(image, norm_mask, model, class_idx)
        
        # Deletion metric (gradually remove important pixels)
        deletion_scores = self._compute_deletion_scores(image, norm_mask, model, class_idx)
        
        # Calculate AUC for insertion and deletion
        insertion_auc = np.trapz(insertion_scores) / len(insertion_scores)
        deletion_auc = 1 - np.trapz(deletion_scores) / len(deletion_scores)
        
        return {
            "insertion_auc": insertion_auc,
            "deletion_auc": deletion_auc,
            "orig_score": orig_score,
            "insertion_scores": insertion_scores,
            "deletion_scores": deletion_scores
        }
    
    def _compute_insertion_scores(self, image, mask, model, class_idx, steps=20):
        """Compute insertion scores by gradually revealing the image."""
        h, w = mask.shape
        scores = []
        
        # Create blurred version of the image
        blurred_image = self._create_blurred_image(image)
        
        # Sort mask values
        flat_mask = mask.flatten()
        indices = np.argsort(flat_mask)[::-1]  # Descending order
        
        # Gradually insert important regions
        for step in range(steps + 1):
            # Create a binary mask for this step
            binary_mask = np.zeros_like(flat_mask)
            
            if step > 0:
                # Reveal the most important pixels
                reveal_count = int((step / steps) * len(indices))
                binary_mask[indices[:reveal_count]] = 1
            
            # Reshape mask
            binary_mask = binary_mask.reshape(h, w)
            
            # Apply mask to blend original and blurred images
            perturbed_image = self._apply_mask_to_image(image, blurred_image, binary_mask)
            
            # Get prediction score
            with torch.no_grad():
                output, _ = model(perturbed_image)
                probs = torch.nn.functional.softmax(output, dim=1)
                score = probs[0, class_idx].item()
            
            scores.append(score)
        
        return np.array(scores)
    
    def _compute_deletion_scores(self, image, mask, model, class_idx, steps=20):
        """Compute deletion scores by gradually removing important regions."""
        h, w = mask.shape
        scores = []
        
        # Create blurred version of the image
        blurred_image = self._create_blurred_image(image)
        
        # Sort mask values
        flat_mask = mask.flatten()
        indices = np.argsort(flat_mask)[::-1]  # Descending order
        
        # Gradually delete important regions
        for step in range(steps + 1):
            # Create a binary mask for this step
            binary_mask = np.ones_like(flat_mask)
            
            if step > 0:
                # Remove the most important pixels
                remove_count = int((step / steps) * len(indices))
                binary_mask[indices[:remove_count]] = 0
            
            # Reshape mask
            binary_mask = binary_mask.reshape(h, w)
            
            # Apply mask to blend original and blurred images
            perturbed_image = self._apply_mask_to_image(image, blurred_image, binary_mask)
            
            # Get prediction score
            with torch.no_grad():
                output, _ = model(perturbed_image)
                probs = torch.nn.functional.softmax(output, dim=1)
                score = probs[0, class_idx].item()
            
            scores.append(score)
        
        return np.array(scores)
    
    def _create_blurred_image(self, image, sigma=10):
        """Create a blurred version of the image."""
        # Convert to numpy and apply gaussian blur
        np_image = image.clone().cpu().squeeze(0).permute(1, 2, 0).numpy()
        blurred = gaussian_filter(np_image, sigma=(sigma, sigma, 0))
        
        # Convert back to tensor
        blurred_tensor = torch.from_numpy(blurred).permute(2, 0, 1).unsqueeze(0).to(image.device)
        return blurred_tensor
    
    def _apply_mask_to_image(self, original, blurred, mask):
        """Apply binary mask to blend original and blurred images."""
        # Expand mask to match image dimensions
        expanded_mask = np.expand_dims(mask, axis=2)  # (H, W, 1)
        expanded_mask = np.repeat(expanded_mask, 3, axis=2)  # (H, W, 3)
        
        # Convert to tensor with same shape as images
        mask_tensor = torch.from_numpy(expanded_mask).permute(2, 0, 1).unsqueeze(0).float().to(original.device)
        
        # Blend images
        perturbed = original * mask_tensor + blurred * (1 - mask_tensor)
        return perturbed


class TextualExplanationEvaluator:
    """
    Evaluator for textual explanations.
    
    Implements metrics to assess the quality, informativeness,
    and relevance of natural language explanations.
    """
    
    def __init__(self):
        """Initialize the textual explanation evaluator."""
        # Try to download NLTK data if needed
        try:
            nltk.data.find('tokenizers/punkt')
        except LookupError:
            nltk.download('punkt', quiet=True)
    
    def evaluate_informativeness(self, explanation, reference_explanations):
        """
        Evaluate how informative the explanation is compared to references.
        
        Args:
            explanation (str): Generated explanation
            reference_explanations (list): List of reference explanations
            
        Returns:
            dict: Informativeness metrics
        """
        if not reference_explanations:
            return {
                "bleu_score": None,
                "note": "No reference explanations provided"
            }
        
        # Tokenize explanations
        candidate_tokens = word_tokenize(explanation.lower())
        reference_tokens = [word_tokenize(ref.lower()) for ref in reference_explanations]
        
        # Calculate BLEU score (up to 4-grams)
        weights = [(1, 0, 0, 0), (0.5, 0.5, 0, 0), (0.33, 0.33, 0.33, 0), (0.25, 0.25, 0.25, 0.25)]
        bleu_scores = []
        
        for weight in weights:
            try:
                score = sentence_bleu(reference_tokens, candidate_tokens, weights=weight)
                bleu_scores.append(score)
            except Exception as e:
                bleu_scores.append(0)
                print(f"Error calculating BLEU score: {e}")
        
        return {
            "bleu_1": bleu_scores[0],
            "bleu_2": bleu_scores[1],
            "bleu_3": bleu_scores[2],
            "bleu_4": bleu_scores[3],
            "avg_bleu": sum(bleu_scores) / len(bleu_scores)
        }
    
    def evaluate_content(self, explanation, expected_content):
        """
        Evaluate if the explanation contains expected content.
        
        Args:
            explanation (str): Generated explanation
            expected_content (list): List of content elements that should be present
            
        Returns:
            dict: Content metrics
        """
        # Count how many expected content elements are present
        presence_count = sum(1 for content in expected_content if content.lower() in explanation.lower())
        coverage = presence_count / len(expected_content) if expected_content else 0
        
        return {
            "content_coverage": coverage,
            "present_elements": presence_count,
            "total_elements": len(expected_content)
        }


